# --------------------- Главное меню ---------------------
def main_menu_keyboard():
    keyboard = [
        [InlineKeyboardButton("📘 О проекте", callback_data="about")],
        [InlineKeyboardButton("👨‍💻 Разработчики сайта", callback_data="devs")],
        [InlineKeyboardButton("👥 Участники проекта", callback_data="participants")],
        [InlineKeyboardButton("🏢 О компании", callback_data="company")],
        [InlineKeyboardButton("📖 Журнал разработки", callback_data="journal")],
    ]
    return InlineKeyboardMarkup(keyboard)

# --------------------- Обработчики ---------------------
async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Привет! Я бот проекта «Центр БЛАГО».\nВыбери раздел:",
        reply_markup=main_menu_keyboard(),
        parse_mode="HTML"
    )

async def button_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()  # обязательно, чтобы убрать "часики" на кнопке

    # Сопоставляем callback_data с нужным текстом
    texts = {
        "about": ABOUT_PROJECT,
        "devs": DEVELOPERS,
        "participants": PARTICIPANTS,
        "company": ABOUT_COMPANY,
        "journal": JOURNAL,
    }

    text = texts.get(query.data, "Раздел не найден.")
    await query.edit_message_text(
        text=text,
        reply_markup=main_menu_keyboard(),  # возвращаем меню
        parse_mode="HTML"
    )

# --------------------- Точка входа ---------------------
def main():
    if not TOKEN:
        raise ValueError("Не найден BOT_TOKEN. Проверьте файл .env")

    app = Application.builder().token(TOKEN).build()

    app.add_handler(CommandHandler("start", start))
    app.add_handler(CallbackQueryHandler(button_handler))

    print("Бот запущен...")
    app.run_polling()

if __name__ == "__main__":
    main()